path = r'D:\SteamLibrary\steamapps\common\Axiom Verge 2\.gemini\superpowers\specs\Content\Text\Dialogue.csv'
out_rows = []
with open(path, 'r', encoding='utf-8') as f:
    reader = csv.reader(f)
    header = next(reader)
    out_rows.append(header)
    
    line_count = 1
    idx = 0
    for row in reader:
        lines_in_row = 1 + sum(field.count('\n') for field in row)
        if line_count + lines_in_row > 200:
            break
            
        if idx in translations:
            row[8] = translations[idx].replace('""', '"')
            
        out_rows.append(row)
        line_count += lines_in_row
        idx += 1

output = io.StringIO()
writer = csv.writer(output, lineterminator='\n')
writer.writerows(out_rows)

with open('final_csv.csv', 'w', encoding='utf-8', newline='') as f:
    f.write(output.getvalue())
